    const cols = stmt.columns().map(col => ({ name: col.name }));
    let rows = [], affected_row_count = 0;
    if (cols.length) rows = stmt.all(...values).map(row => cols.map(col => row[col.name] == null ? { type: 'null' } : { type: 'text', value: String(row[col.name]) }));
